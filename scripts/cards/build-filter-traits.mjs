import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');

/** Use explicit body lengths only, never infer body size from wing/tarsus/mass.
 * Read cm ranges before optional imperial conversions; reject unsupported or implausible values.
 */
export function parseBodyLength(raw) {
  if (typeof raw !== 'string') return null;
  const match = raw.trim().match(/^(?:(?:約|大約|about|approx\.?)\s*)?(\d+(?:\.\d+)?)(?:\s*(?:cm|厘米|公分))?(?:\s*[–—−\-~至到]\s*(\d+(?:\.\d+)?))?\s*(?:cm|厘米|公分)(?:\s*[（(].*)?$/i);
  if (!match) return null;
  const lo = Number(match[1]);
  const hi = match[2] ? Number(match[2]) : lo;
  if (lo < 5 || hi > 300 || lo > hi) return null;
  return Math.round((lo + hi) / 2 * 10) / 10;
}

export function parseConservation(raw) {
  return typeof raw === 'string' ? raw.match(/\b(LC|NT|VU|EN|CR|EW|EX|DD|NE)\b/i)?.[1]?.toUpperCase() || 'UNKNOWN' : 'UNKNOWN';
}

export function buildFilterTraits(birds, copy, details) {
  return Object.fromEntries(birds.map(({ id }) => [id, {
    lengthCm: parseBodyLength(copy[id]?.length),
    iucn: parseConservation(details[id]?.iucn),
  }]));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const read = name => JSON.parse(fs.readFileSync(path.join(ROOT, 'src/data', name), 'utf8'));
  const traits = buildFilterTraits(read('birds.json'), read('cardCopy.json'), read('cardDetails.zh.json').birds);
  fs.writeFileSync(path.join(ROOT, 'src/data/filterTraits.json'), JSON.stringify({
    _note: 'Generated by npm run cards:filters. Body length (cm, range midpoint) from cardCopy.length; IUCN from cardDetails.zh.iucn, same as card scores. Missing/invalid data stays unknown. These are global threat categories, not local HK sighting frequency.',
    birds: traits,
  }) + '\n');
  console.log(`Filter traits: ${Object.keys(traits).length} birds, ${Object.values(traits).filter(t => t.lengthCm !== null).length} with explicit body length`);
}
