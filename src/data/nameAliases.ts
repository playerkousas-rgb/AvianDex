/** 把 AI 辨識或搜尋輸入的鳥名（英文俗名 / 學名 / 繁簡中文）轉成 4 位圖鑑 ID。 */
export function resolveBirdId(label: string): string | null {
  if (!label) return null;
  const key = label.trim().toLowerCase();
  if (!key) return null;
  if (NAME_TO_ID[key]) return NAME_TO_ID[key];
  if (key.includes('_')) {
    const parts = key.split('_').map((s) => s.trim()).filter(Boolean);
    for (const part of parts) {
      if (NAME_TO_ID[part]) return NAME_TO_ID[part];
    }
  }
  const norm = (s: string) => s.replace(/[\s\-'’._()（）]+/g, '');
  const normKey = norm(key);
  if (normKey) {
    for (const [aliasKey, id] of Object.entries(NAME_TO_ID)) {
      if (norm(aliasKey) === normKey) return id;
    }
  }
  if (key.length >= 2) {
    let bestId: string | null = null;
    let bestLen = 0;
    for (const [aliasKey, id] of Object.entries(NAME_TO_ID)) {
      if (aliasKey.length < 2) continue;
      if (key.includes(aliasKey) && aliasKey.length > bestLen) {
        bestLen = aliasKey.length;
        bestId = id;
      }
    }
    if (bestId) return bestId;
  }
  return null;
}
